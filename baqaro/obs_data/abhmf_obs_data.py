"""Observed active black-hole mass functions (BHMF) at z = 0.2 - 6.

Number density of *active* (quasar-selected) black holes per dex of M_BH, the
observational counterpart of the model's QBHMF. Entries are keyed by redshift
string in ``data_bhmf_global`` and wrapped in :class:`BHMF_data`.

Sources: Schulze+2010 (z=0.2), He+2024 (z=4), Lai+2024 and Matthee+2024 (z=5),
Wu+2022 (z=6).

Because these are ACTIVE BHMFs they must be compared against the model's
luminosity-selected black holes, not against all of them -- see the local BHMF
in :mod:`local_bhmf_obs_data` for the total-population measurements at z ~ 0.
"""

import numpy as np


class BHMF_data:
    """One published active-BHMF measurement.

    Parameters
    ----------
    x_data, y_data : array_like
        log10(M_BH / Msun) bin centres and log10(phi / dex^-1 cMpc^-3).
    errs : (array_like, array_like)
        ``[err_down, err_up]`` in dex. Infinities are tolerated -- upper
        limits are published that way -- and are excluded from the symmetric
        ``.err`` average rather than poisoning it.
    label : str
        Display label, conventionally "Author+Year z=Z".
    """

    def __init__(self, x_data, y_data, errs, label):
        self.x = x_data

        self.data = y_data

        self.errs = errs

        self.err_down = errs[0]
        self.err_up = errs[1]
        
        # Handle inf values: replace with finite values or skip averaging
        err_down_finite = np.where(np.isfinite(self.err_down), self.err_down, 0)
        err_up_finite = np.where(np.isfinite(self.err_up), self.err_up, 0)
        self.err = (err_down_finite + err_up_finite) / 2.

        self.label = label


    def check_nans(self):
        var = np.asarray(self.data)

        return np.isnan(np.sum(var))



