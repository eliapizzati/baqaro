# KS13 sample & completeness (from arXiv:1209.0477):
#   Type 1 (broad-line) QUASARS, ~58,000, uniformly selected from SDSS DR7
#   with the Richards+2006 selection function; flux-limited at i < 19.1
#   (z < 2.9) and i < 20.2 (z > 2.9). Virial M_BH from broad-line widths.
#   Each entry is the posterior-median BHMF with the 68% credible region
#   (Table 1: z, logM, lo, logPhi_median, up); err_down=logPhi-lo,
#   err_up=up-logPhi.
#   *** COMPLETENESS: KS13 is "highly incomplete below M_BH ~ 3e8 Msun"
#   (logM < ~8.5); below that the BHMF is an extrapolation the authors call
#   "highly uncertain". That sub-completeness regime (huge, asymmetric error
#   bars; non-monotonic medians) is the "weird"-looking part of the curve.
# We DROP the z=4.75 bin entirely: the DR7 sample is essentially
# unconstrained at that redshift, and via the per-z plotters' 0.3 fuzzy
# match it would otherwise mis-populate the z=5 panel with a clearly-wrong
# BHMF.
_KS13_EXCLUDE_Z = {4.75}
# Parse into per-redshift BHMF_data objects
_ks13_redshifts = np.unique(_ks13_raw[:, 0])
for _z in _ks13_redshifts:
    if _z in _KS13_EXCLUDE_Z:
        continue
    _mask = _ks13_raw[:, 0] == _z
    _logM = _ks13_raw[_mask, 1]
    _logPhi = _ks13_raw[_mask, 3]       # median
    _lo = _ks13_raw[_mask, 2]           # lower bound
    _up = _ks13_raw[_mask, 4]           # upper bound
    _err_down = _logPhi - _lo           # positive: logPhi - lo
    _err_up = _up - _logPhi             # positive: up - logPhi
    _key = f'{_z:.1f}' if _z == int(_z) else f'{_z:.3f}'
    data_bhmf_global[f'KS13_{_key}'] = BHMF_data(
        x_data=_logM, y_data=_logPhi,
        errs=[_err_down, _err_up],
        label=f"Kelly&Shen13 z={_z}"
    )
