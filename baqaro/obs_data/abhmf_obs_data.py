#
# SOURCE: taken from the AUTHORS' OWN DATA RELEASE
#   https://github.com/wanqqq31/BHMF_hsc_z4  ->  BHMF_ERDF/binBHMF.csv
#   (columns `log M_BH`, `Phi_tot`, `Phi_tot_err`, in Mpc^-3 dex^-1),
# NOT the paper's Table 8, which is printed rounded to 2 dp in units of 1e-7 and
# whose rounding loses two real measurements:
#   * logM = 10.8 : Table 8 prints "0.00"; the CSV gives Phi = 6.46e-11 with
#                   N_tot = 1. It is a real one-object bin, not an empty one.
#   * logM = 10.5 : Table 8's error rounds to "0.00"; the CSV gives 2.89e-10 on
#                   1.29e-9 (22%).
# The CSV reproduces Table 8 wherever Table 8 has precision (1.21e-06 / 9.92e-07
# at logM = 7.5 / 7.8), so this is strictly a precision upgrade, not a different
# measurement.
# --------------------------------------------------------------------------
key = '4.0'
x_data_z4 = np.array([7.5, 7.8, 8.1, 8.4, 8.7, 9.0, 9.3, 9.6, 9.9, 10.2, 10.5, 10.8])
# Phi and its (symmetric, linear) error, Mpc^-3 dex^-1 — verbatim from binBHMF.csv.
_phi_z4 = np.array([1.21e-06, 9.92e-07, 1.13e-06, 1.39e-06, 8.07e-07, 4.46e-07,
                    4.94e-08, 1.61e-07, 1.91e-08, 4.33e-09, 1.29e-09, 6.46e-11])
_err_z4 = np.array([8.70e-07, 6.24e-07, 4.34e-07, 3.68e-07, 2.87e-07, 1.89e-07,
                    2.79e-08, 1.08e-07, 1.11e-09, 5.29e-10, 2.89e-10, 6.46e-11])
with np.errstate(divide="ignore", invalid="ignore"):
    y_data_z4 = np.log10(_phi_z4)
    y_data_err_up_z4 = np.log10(_phi_z4 + _err_z4) - y_data_z4
    # Phi - err <= 0 for the 1-object bins (err == Phi) -> the lower bar is
    # unbounded. Cap it at 1.5 dex so matplotlib draws a finite "consistent with
    # zero" bar instead of a line to the axis edge.
    _lo_z4 = np.clip(_phi_z4 - _err_z4, 1e-30, None)
    y_data_err_down_z4 = np.clip(y_data_z4 - np.log10(_lo_z4), 0.0, 1.5)

data_bhmf_global[key] = BHMF_data(x_data=x_data_z4, y_data=y_data_z4,
                                   errs=[y_data_err_down_z4, y_data_err_up_z4],
                                   label="He+2024 z=4.0")

