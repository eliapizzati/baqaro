"""Cosmic black-hole mass density rho_BH(z), the integral constraint.

Total mass locked in black holes per comoving volume as a function of redshift,
in ``data_cbhmd`` as :class:`CBHMD_data` entries. This is the time-integrated
counterpart of the accretion-rate density in :mod:`cbhad_obs_data`: a model can
match the QLF at every epoch and still fail here if its radiative efficiency or
seeding is wrong, which makes it a useful independent check rather than another
view of the same information.

The compilation mixes measurement types deliberately -- integrated-QLF
estimates (Marconi+2004, Shankar+2013, Shen+2020), an X-ray-derived one
(Merloni & Heinz 2008), and semi-analytic predictions (Ricarte & Natarajan
2018, Santa Cruz SAM) -- so check each entry's label before treating a spread
between them as an observational uncertainty.
"""

import numpy as np


class CBHMD_data:
    """Cosmic Black Hole Mass Density data container."""

    def __init__(self, z_data, y_data, errs, label):
        self.z = z_data
        self.data = y_data  # log(rho_bh) [Msun Mpc^-3]
        self.errs = errs
        self.err_down = errs[0]
        self.err_up = errs[1]
        err_down_finite = np.where(np.isfinite(self.err_down), self.err_down, 0)
        err_up_finite = np.where(np.isfinite(self.err_up), self.err_up, 0)
        self.err = (err_down_finite + err_up_finite) / 2.
        self.label = label


data_cbhmd = {}

